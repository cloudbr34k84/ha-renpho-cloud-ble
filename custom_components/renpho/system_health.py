from __future__ import annotations

from typing import Any

from homeassistant.components import system_health
from homeassistant.core import HomeAssistant, callback

from .cloud_api import API_BASE
from .const import CONF_SOURCE, DOMAIN, SOURCE_BLE, SOURCE_CLOUD


@callback
def async_register(hass: HomeAssistant, register: system_health.SystemHealthRegistration) -> None:
    register.async_register_info(system_health_info)


async def system_health_info(hass: HomeAssistant) -> dict[str, Any]:
    sources = [e.data.get(CONF_SOURCE) for e in hass.config_entries.async_entries(DOMAIN)]
    info: dict[str, Any] = {
        "cloud_accounts": sources.count(SOURCE_CLOUD),
        "bluetooth_scales": sources.count(SOURCE_BLE),
    }
    if SOURCE_CLOUD in sources:
        info["can_reach_server"] = system_health.async_check_can_reach_url(hass, API_BASE)
    return info
